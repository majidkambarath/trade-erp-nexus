// Put the made videos into the app: shrink each into public/videos/, and write src/guides/videos.js, the list the
// Learn page reads to decide whether a guide has a video in a language.
//   FFMPEG=<path to ffmpeg> node scripts/videos/publish.mjs
// The pictures are stills held for each spoken card, so 10 frames a second and a high CRF lose nothing visible;
// speech needs no more than mono 40 kb/s. A file that is already published and newer than its source is skipped.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const src = path.join(here, "out");
const dest = path.join(root, "public", "videos");
const ffmpeg = process.env.FFMPEG || "ffmpeg";
fs.mkdirSync(dest, { recursive: true });

const NAME = /^([a-z0-9-]+)\.(en|ml)\.mp4$/;
const made = fs.readdirSync(src).filter((f) => NAME.test(f));
let shrunk = 0;
for (const f of made) {
  const from = path.join(src, f);
  const to = path.join(dest, f);
  if (fs.existsSync(to) && fs.statSync(to).mtimeMs >= fs.statSync(from).mtimeMs) continue;
  const r = spawnSync(ffmpeg, ["-y", "-v", "error", "-i", from, "-r", "10", "-c:v", "libx264", "-preset", "slow", "-tune", "stillimage",
    "-crf", "32", "-pix_fmt", "yuv420p", "-c:a", "aac", "-ac", "1", "-b:a", "40k", "-movflags", "+faststart", to], { encoding: "utf8" });
  if (r.status !== 0) { console.error(`could not shrink ${f}: ${r.stderr}`); process.exitCode = 1; continue; }
  shrunk += 1;
}

// The list, from what is actually in public/videos (so a file removed by hand is no longer offered).
const list = {};
for (const f of fs.readdirSync(dest).filter((x) => NAME.test(x)).sort()) {
  const [, id, lang] = f.match(NAME);
  (list[id] ||= []).push(lang);
}
const body = Object.entries(list).map(([id, langs]) => `  "${id}": [${langs.sort().map((l) => `"${l}"`).join(", ")}],`).join("\n");
fs.writeFileSync(path.join(root, "src", "guides", "videos.js"), `// GENERATED by scripts/videos/publish.mjs - do not edit by hand. Which guides have a walkthrough video, and in
// which languages. The files are public/videos/<guide>.<lang>.mp4 (made by scripts/videos/make.mjs).
export const VIDEOS = {
${body}
};

// The video for a guide in a language, falling back to English; null when there is none.
export function videoUrl(id, lang) {
  const langs = VIDEOS[id];
  if (!langs) return null;
  const use = langs.includes(lang) ? lang : langs.includes("en") ? "en" : null;
  return use ? { src: \`/videos/\${id}.\${use}.mp4\`, lang: use } : null;
}
`);
const size = fs.readdirSync(dest).reduce((n, f) => n + fs.statSync(path.join(dest, f)).size, 0);
console.log(`published ${Object.keys(list).length} guides (${shrunk} files shrunk now), ${(size / 1048576).toFixed(1)} MB in public/videos`);
